def describe_dependency(name: str) -> dict[str, str | None]:
    if name in _CATALOG:
        category, description = _CATALOG[name]
        return {"category": category, "description": description}
    for prefix, category, description in _PREFIX_RULES:
        if name.startswith(prefix):
            if prefix == "@types/":
                description = f"TypeScript types for {name[len(prefix):]}"
            return {"category": category, "description": description}
    return {"category": "Other", "description": None}
